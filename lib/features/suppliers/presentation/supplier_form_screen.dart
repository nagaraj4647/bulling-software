import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:go_router/go_router.dart';

import '../../../core/utils/error_formatter.dart';
import '../../business/providers/business_provider.dart';
import '../providers/supplier_provider.dart';
import '../models/supplier_model.dart';

class SupplierFormScreen extends ConsumerStatefulWidget {
  final String? supplierId; // If null, we are creating a new supplier

  const SupplierFormScreen({super.key, this.supplierId});

  @override
  ConsumerState<SupplierFormScreen> createState() => _SupplierFormScreenState();
}

class _SupplierFormScreenState extends ConsumerState<SupplierFormScreen> {
  final _formKey = GlobalKey<FormState>();

  final _nameController = TextEditingController();
  final _phoneController = TextEditingController();
  final _emailController = TextEditingController();
  final _addressController = TextEditingController();
  final _cityController = TextEditingController();
  final _stateController = TextEditingController();
  final _pincodeController = TextEditingController();
  final _gstNumberController = TextEditingController();
  final _openingBalanceController = TextEditingController();

  bool _isActive = true;
  SupplierModel? _existingSupplier;
  bool _isLoading = false;

  @override
  void initState() {
    super.initState();
    if (widget.supplierId != null) {
      _loadSupplier();
    }
  }

  Future<void> _loadSupplier() async {
    setState(() => _isLoading = true);
    try {
      final supplier = await ref.read(
        supplierDetailsProvider(widget.supplierId!).future,
      );
      if (supplier != null) {
        _existingSupplier = supplier;
        _nameController.text = supplier.name;
        _phoneController.text = supplier.phone ?? '';
        _emailController.text = supplier.email ?? '';
        _addressController.text = supplier.address ?? '';
        _cityController.text = supplier.city ?? '';
        _stateController.text = supplier.state ?? '';
        _pincodeController.text = supplier.pincode ?? '';
        _gstNumberController.text = supplier.gstNumber ?? '';
        _openingBalanceController.text = supplier.openingBalance.toString();
        _isActive = supplier.isActive;
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(
          context,
        ).showSnackBar(SnackBar(content: Text('Error loading supplier: $e')));
      }
    } finally {
      if (mounted) {
        setState(() => _isLoading = false);
      }
    }
  }

  @override
  void dispose() {
    _nameController.dispose();
    _phoneController.dispose();
    _emailController.dispose();
    _addressController.dispose();
    _cityController.dispose();
    _stateController.dispose();
    _pincodeController.dispose();
    _gstNumberController.dispose();
    _openingBalanceController.dispose();
    super.dispose();
  }

  // Generate searchable prefixes
  List<String> _generateSearchKeywords(String name, String phone, String code) {
    final Set<String> keywords = {};

    void addPrefixes(String word) {
      final w = word.trim().toLowerCase();
      for (int i = 1; i <= w.length; i++) {
        keywords.add(w.substring(0, i));
      }
    }

    // Split name into words and add prefixes for each word
    final nameWords = name.split(RegExp(r'\s+'));
    for (var word in nameWords) {
      addPrefixes(word);
    }

    if (phone.isNotEmpty) addPrefixes(phone);
    if (code.isNotEmpty) addPrefixes(code);

    return keywords.toList();
  }

  Future<void> _saveSupplier() async {
    if (!_formKey.currentState!.validate()) return;

    final business = ref.read(currentBusinessProvider).value;
    if (business == null) return;

    final name = _nameController.text.trim();
    final phone = _phoneController.text.trim();
    final email = _emailController.text.trim();
    final address = _addressController.text.trim();
    final city = _cityController.text.trim();
    final state = _stateController.text.trim();
    final pincode = _pincodeController.text.trim();
    final gstNumber = _gstNumberController.text.trim();
    final openingBalance =
        double.tryParse(_openingBalanceController.text.trim()) ?? 0.0;

    final searchKeywords = _generateSearchKeywords(
      name,
      phone,
      _existingSupplier?.supplierCode ?? '',
    );

    try {
      if (_existingSupplier == null) {
        // Create new
        final newSupplier = SupplierModel(
          supplierId: '', // Generated by Firestore
          businessId: business.businessId!,
          supplierCode: '', // Generated by transaction
          name: name,
          phone: phone.isNotEmpty ? phone : null,
          email: email.isNotEmpty ? email : null,
          address: address.isNotEmpty ? address : null,
          city: city.isNotEmpty ? city : null,
          state: state.isNotEmpty ? state : null,
          pincode: pincode.isNotEmpty ? pincode : null,
          gstNumber: gstNumber.isNotEmpty ? gstNumber : null,
          searchKeywords: searchKeywords, // The service will need to update keywords with the new code ideally, but we can just use name/phone for now or let Cloud Functions do it. We'll generate it here for now.
          openingBalance: openingBalance,
          outstandingBalance:
              openingBalance, // Enforce same as openingBalance on create
          isActive: _isActive,
          createdAt: DateTime.now(),
          updatedAt: DateTime.now(),
        );
        await ref
            .read(supplierControllerProvider.notifier)
            .createSupplier(newSupplier);
      } else {
        // Update existing
        final updatedSupplier = _existingSupplier!.copyWith(
          name: name,
          phone: phone.isNotEmpty ? phone : null,
          email: email.isNotEmpty ? email : null,
          address: address.isNotEmpty ? address : null,
          city: city.isNotEmpty ? city : null,
          state: state.isNotEmpty ? state : null,
          pincode: pincode.isNotEmpty ? pincode : null,
          gstNumber: gstNumber.isNotEmpty ? gstNumber : null,
          searchKeywords: searchKeywords,
          isActive: _isActive,
          updatedAt: DateTime.now(),
          // Note: copyWith protects openingBalance. outstandingBalance is preserved.
        );
        await ref
            .read(supplierControllerProvider.notifier)
            .updateSupplier(updatedSupplier);
      }

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Supplier saved successfully')),
        );
        context.pop();
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(
              'Failed to save supplier: ${ErrorFormatter.format(e)}',
            ),
            backgroundColor: Colors.red,
          ),
        );
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final isEditing = widget.supplierId != null;
    final isSaving = ref.watch(supplierControllerProvider).isLoading;

    return Scaffold(
      appBar: AppBar(title: Text(isEditing ? 'Edit Supplier' : 'Add Supplier')),
      body: _isLoading
          ? const Center(child: CircularProgressIndicator())
          : SingleChildScrollView(
              padding: const EdgeInsets.all(16.0),
              child: Form(
                key: _formKey,
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.stretch,
                  children: [
                    Text(
                      'Basic Details',
                      style: Theme.of(context).textTheme.titleMedium,
                    ),
                    const SizedBox(height: 16),
                    TextFormField(
                      controller: _nameController,
                      decoration: const InputDecoration(
                        labelText: 'Supplier Name *',
                        border: OutlineInputBorder(),
                      ),
                      validator: (value) =>
                          value == null || value.trim().isEmpty
                          ? 'Name is required'
                          : null,
                    ),
                    const SizedBox(height: 16),
                    Row(
                      children: [
                        Expanded(
                          child: TextFormField(
                            controller: _phoneController,
                            decoration: const InputDecoration(
                              labelText: 'Phone',
                              border: OutlineInputBorder(),
                            ),
                            keyboardType: TextInputType.phone,
                          ),
                        ),
                        const SizedBox(width: 16),
                        Expanded(
                          child: TextFormField(
                            controller: _emailController,
                            decoration: const InputDecoration(
                              labelText: 'Email',
                              border: OutlineInputBorder(),
                            ),
                            keyboardType: TextInputType.emailAddress,
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 32),

                    Text(
                      'Address & Tax',
                      style: Theme.of(context).textTheme.titleMedium,
                    ),
                    const SizedBox(height: 16),
                    TextFormField(
                      controller: _addressController,
                      decoration: const InputDecoration(
                        labelText: 'Address',
                        border: OutlineInputBorder(),
                      ),
                    ),
                    const SizedBox(height: 16),
                    Row(
                      children: [
                        Expanded(
                          child: TextFormField(
                            controller: _cityController,
                            decoration: const InputDecoration(
                              labelText: 'City',
                              border: OutlineInputBorder(),
                            ),
                          ),
                        ),
                        const SizedBox(width: 16),
                        Expanded(
                          child: TextFormField(
                            controller: _stateController,
                            decoration: const InputDecoration(
                              labelText: 'State',
                              border: OutlineInputBorder(),
                            ),
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 16),
                    Row(
                      children: [
                        Expanded(
                          child: TextFormField(
                            controller: _pincodeController,
                            decoration: const InputDecoration(
                              labelText: 'Pincode',
                              border: OutlineInputBorder(),
                            ),
                          ),
                        ),
                        const SizedBox(width: 16),
                        Expanded(
                          child: TextFormField(
                            controller: _gstNumberController,
                            decoration: const InputDecoration(
                              labelText: 'GST Number',
                              border: OutlineInputBorder(),
                            ),
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 32),

                    Text(
                      'Financials',
                      style: Theme.of(context).textTheme.titleMedium,
                    ),
                    const SizedBox(height: 16),
                    TextFormField(
                      controller: _openingBalanceController,
                      decoration: const InputDecoration(
                        labelText: 'Opening Balance (Payable)',
                        border: OutlineInputBorder(),
                        prefixText: '₹ ',
                      ),
                      keyboardType: const TextInputType.numberWithOptions(
                        decimal: true,
                      ),
                      enabled: !isEditing, // Immutable after creation
                      validator: (value) {
                        if (value == null || value.trim().isEmpty) return null;
                        final parsed = double.tryParse(value);
                        if (parsed == null) return 'Enter a valid number';
                        if (parsed < 0) return 'Balance cannot be negative';
                        return null;
                      },
                    ),
                    if (isEditing)
                      const Padding(
                        padding: EdgeInsets.only(top: 8.0),
                        child: Text(
                          'Opening balance cannot be modified after creation.',
                          style: TextStyle(fontSize: 12, color: Colors.grey),
                        ),
                      ),

                    const SizedBox(height: 32),
                    SwitchListTile(
                      title: const Text('Active Status'),
                      subtitle: const Text(
                        'Inactive suppliers will not appear in purchases.',
                      ),
                      value: _isActive,
                      onChanged: (val) => setState(() => _isActive = val),
                    ),
                    const SizedBox(height: 32),

                    FilledButton.icon(
                      onPressed: isSaving ? null : _saveSupplier,
                      icon: isSaving
                          ? const SizedBox(
                              width: 16,
                              height: 16,
                              child: CircularProgressIndicator(
                                color: Colors.white,
                                strokeWidth: 2,
                              ),
                            )
                          : const Icon(Icons.save),
                      label: Text(isSaving ? 'Saving...' : 'Save Supplier'),
                    ),
                    const SizedBox(height: 32),
                  ],
                ),
              ),
            ),
    );
  }
}
